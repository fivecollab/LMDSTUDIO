-- Schéma du site LMD Studios. À exécuter une fois dans Supabase : SQL Editor > New query > Run.

create table if not exists reglages (
  cle text primary key,
  valeur text not null default ''
);

create table if not exists medias (
  id bigint generated by default as identity primary key,
  type text not null check (type in ('img', 'video')),
  url text not null,
  poster text,
  chemin text,          -- chemin dans le bucket « medias » (null pour les fichiers livrés avec le site)
  poster_chemin text,
  largeur int not null, -- dimensions d'origine, pour respecter les proportions exactes
  hauteur int not null,
  nom text not null default '',
  cree_le timestamptz not null default now()
);

create table if not exists collage (
  id bigint generated by default as identity primary key,
  format text not null check (format in ('desktop', 'tablette', 'mobile')),
  media_id bigint not null references medias(id) on delete cascade,
  x real not null,
  y real not null,
  w real not null,
  h real not null,
  a real not null default 0,
  ordre int not null default 0
);
create index if not exists collage_format_ordre on collage (format, ordre);

create table if not exists projets (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  titre text not null,
  categorie text not null default '',
  couverture_id bigint references medias(id) on delete set null,
  publie boolean not null default false,
  ordre int not null default 0,
  titre_detail text not null default '',
  client text not null default '',
  annee text not null default '',
  services text not null default '',    -- un service par ligne
  description text not null default '', -- paragraphes séparés par une ligne vide
  galerie jsonb not null default '[]'::jsonb
);

-- Aucun accès public direct : le site lit et écrit uniquement côté serveur (clé service_role).
alter table reglages enable row level security;
alter table medias enable row level security;
alter table collage enable row level security;
alter table projets enable row level security;

